# 현재 조건과 계약

- 창고 직원이 공유 스캐너로 주문을 조회하고 물건을 택배 기사에게 넘긴다. 두 직원이 같은 주문을 동시에 열 수 있다.
- 화면 목록은 15초 전 서버 응답일 수 있다. 창고 안에서는 무선 연결이 끊길 수 있다.
- 기존 화면은 로컬 전송 대기와 서버 출고 확정을 둘 다 '처리됨'으로 표시한다. 로컬 대기만으로는 서버에 기록됐는지 알 수 없다.
- 서버 출고 확정은 200과 출고 기록 ID를 반환한다. 이미 확정된 주문은 409를 반환하고 새 출고 기록을 만들지 않는다. 응답을 잃어도 서버 저장은 성공했을 수 있다.
- 같은 주문의 실제 물건을 두 번 넘기는지 측정하는 현장 기록은 없다. 서버 기록 건수와 실제 인계 횟수는 다른 값이다.
- 실패 후 조회 API와 동시 처리의 원자성에 관한 상세 명세는 이 저장소에 없다. 직원의 기존 조회·출고 권한은 바꾸지 않는다.
- 연결이 끊긴 동안 실제 물건을 넘길 수 있는지 운영자가 정하지 않았다. 최대 대기 시간, 재고 차감 정책, 직원 평가 정책은 이번 범위 밖이다.
- 이번 화면 개선의 우선 목표가 처리 속도인지, 중복 출고 방지인지, 교육 부담 감소인지 아직 정해지지 않았다.
EOF
